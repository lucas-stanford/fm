//! The clock: the tick, `fm serve`, and the watcher (the OS job that ticks once a minute).
//!
//! - [`decide_tick`] / [`decide_one`]: the pure schedule decision (grace, catch-up, claims,
//!   stagger), the same rules as pi-automations' `decideTick`.
//! - [`tick()`]: one pass of the clock against a state folder. Starting a run is injected
//!   ([`StartRun`]); the real one is [`DetachedSpawn`], a detached `fm fire …`.
//! - [`watch`]: the `on.watch` contract (fingerprints, exit semantics, pause).
//! - [`next_fire`], [`next_check`]: what a listing shows about the clock.
//! - [`serve()`]: tick every minute in the foreground, refused while the watcher is registered.
//! - [`watcher`]: register, remove and report the OS job (Task Scheduler, launchd, systemd or
//!   cron). Job files are generated by pure functions; the scheduler commands go through an
//!   injectable [`watcher::Exec`].

