//! The watcher: the OS job that runs one tick every minute (`fm tick --by job`), so schedules fire
//! and watches are checked while no `fm` is open. One per user and state folder:
//!
//! | OS | Job | Files |
//! |---|---|---|
//! | Windows | Task Scheduler task `agent-automations\tick` ([`windows`]) | `<state>\watcher\tick.xml`, `fm-tick.cmd` |
//! | macOS | LaunchAgent `io.agentautomations.fm.tick` ([`macos`]) | `~/Library/LaunchAgents/<label>.plist`, `<state>/watcher/fm-tick.sh` |
//! | Linux | systemd user timer `fm-tick.timer` ([`linux`]), else a crontab line | `~/.config/systemd/user/fm-tick.{service,timer}`, `<state>/watcher/fm-tick.sh` |
//!
//! Every job runs a small wrapper in the state folder that sets the environment carried from the
//! shell that ran `fm watcher start` ([`env`]: `FM_HOME`, `PATH`, …, never a credential), then the
//! absolute executable path; when that binary is gone, the wrapper removes the job instead of failing
//! every minute. `watcher.json` in the state folder records what was registered.
//!
//! The job files are generated by pure functions, tested on every OS. Registration goes through
//! [`Exec`], so tests never touch the real scheduler. pi-automations' own watcher has other names
//! and is never touched.

