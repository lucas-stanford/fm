/// How long `watcher start` waits for the first tick.
pub const FIRST_TICK_WAIT: Duration = Duration::from_secs(90);

/// A tick comes once a minute; five quiet minutes means nothing is ticking.
pub const QUIET: Duration = Duration::from_secs(5 * 60);

/// The job's names in each scheduler. Distinct from pi-automations' (`pi-automations\tick`,
/// `io.agentautomations.pi.tick`, `pi-automations-tick`).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Names {
    /// Windows task name (a folder and a name).
    pub task: String,
    /// macOS launchd label.
    pub label: String,
    /// Linux systemd unit base name and crontab marker.
    pub unit: String,
}

impl Default for Names {
    fn default() -> Self {
        Names {
            task: r"agent-automations\tick".into(),
            label: "io.agentautomations.fm.tick".into(),
            unit: "fm-tick".into(),
        }
    }
}

impl Names {
    /// Names for a test job, which can never collide with a real one.
    pub fn test(suffix: &str) -> Names {
        Names {
            task: format!("fm-test-{suffix}"),
            label: format!("io.agentautomations.fm.test-{suffix}"),
            unit: format!("fm-test-{suffix}"),
        }
    }
}

/// What a job is made of.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct JobSpec {
    /// The absolute host executable.
    pub exe: PathBuf,
    pub state_dir: PathBuf,
    /// Carried environment, `FM_HOME` first.
    pub env: Vec<(String, String)>,
    pub names: Names,
    /// The wrapper the job runs.
    pub script: PathBuf,
    /// Where the tick's output goes.
    pub log: PathBuf,
    /// `watcher.json`.
    pub record: PathBuf,
}

/// A scheduler command.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Cmd {
    pub program: String,
    pub args: Vec<String>,
    pub stdin: Option<String>,
}

impl Cmd {
    pub fn new(program: &str, args: Vec<String>) -> Cmd {
        Cmd {
            program: program.to_string(),
            args,
            stdin: None,
        }
    }
}

impl std::fmt::Display for Cmd {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{} {}", self.program, self.args.join(" "))
    }
}

/// How a command ended. `code` is `None` when it could not run at all.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct ExecResult {
    pub code: Option<i32>,
    pub stdout: String,
    pub stderr: String,
}

impl ExecResult {
    pub fn ok(&self) -> bool {
        self.code == Some(0)
    }

    /// The first non-empty line of what it said, for a one-line message.
    pub fn first_line(&self) -> String {
        self.stderr
            .lines()
            .chain(self.stdout.lines())
            .map(str::trim)
            .find(|l| !l.is_empty())
            .unwrap_or("no output")
            .to_string()
    }
}

/// Runs scheduler commands. [`SystemExec`] is the real one.
pub trait Exec {
    fn exec(&self, cmd: &Cmd) -> ExecResult;
}

/// Runs the command for real, bounded to a minute, with no console window.
#[derive(Debug, Clone, Copy, Default)]
pub struct SystemExec;

impl Exec for SystemExec {
    fn exec(&self, cmd: &Cmd) -> ExecResult {
        let cwd = std::env::temp_dir();
        let mut spec = ProcessSpec::new(&cmd.program, cwd).args(cmd.args.clone());
        spec.env_mode = EnvMode::Inherit {
            overlay: Vec::new(),
        };
        spec.stdin = match &cmd.stdin {
            Some(s) => Stdin::Bytes(s.clone().into_bytes()),
            None => Stdin::Null,
        };
        spec.timeout = Duration::from_secs(60);
        match fm_run::process::run(&spec, |_| {}) {
            ProcessOutcome::Exited { exit, output } => ExecResult {
                code: Some(exit),
                stdout: output.stdout,
                stderr: output.stderr,
            },
            ProcessOutcome::StartFailed { message } => ExecResult {
                code: None,
                stdout: String::new(),
                stderr: message,
            },
            other => ExecResult {
                code: None,
                stdout: other.output().map(|o| o.stdout.clone()).unwrap_or_default(),
                stderr: format!("{} did not finish", cmd.program),
            },
        }
    }
}

/// Which scheduler holds the job.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Method {
    Schtasks,
    Launchd,
    Systemd,
    Crontab,
}

impl Method {
    pub fn word(self) -> &'static str {
        match self {
            Method::Schtasks => "schtasks",
            Method::Launchd => "launchd",
            Method::Systemd => "systemd",
            Method::Crontab => "crontab",
        }
    }
}

/// `watcher.json`: what `fm watcher start` registered.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct WatcherRecord {
    pub version: u32,
    pub method: Method,
    pub job_name: String,
    pub exe: PathBuf,
    pub installed_at: String,
    /// The job files written, removed again by `fm watcher stop`.
    #[serde(default)]
    pub files: Vec<PathBuf>,
    /// Credential-shaped variables deliberately not carried.
    #[serde(default)]
    pub refused: Vec<String>,
}

pub fn record_path(paths: &StatePaths) -> PathBuf {
    paths.root.join("watcher.json")
}

pub fn read_record(paths: &StatePaths) -> Option<WatcherRecord> {
    let text = std::fs::read_to_string(record_path(paths)).ok()?;
    serde_json::from_str(&text).ok()
}

/// Is the watcher job registered for this state folder?
pub fn watcher_registered(paths: &StatePaths) -> bool {
    record_path(paths).exists()
}

/// Everything the watcher verbs need from the machine. [`WatcherContext::system`] is the real one.
pub struct WatcherContext<'a> {
    pub os: Os,
    pub paths: StatePaths,
    pub home: PathBuf,
    pub exec: &'a dyn Exec,
    /// The environment to carry from (this process's, for real).
    pub env: Vec<(String, String)>,
    pub names: Names,
    /// Windows: `%SystemRoot%`.
    pub system_root: PathBuf,
    /// How long `start` waits for the first tick; zero does not wait.
    pub wait: Duration,
    pub clock: &'a dyn Clock,
    /// The running executable, to notice a job registered for another one.
    pub current_exe: Option<PathBuf>,
}

impl WatcherContext<'static> {
    /// This machine, this user, the default job names.
    pub fn system(paths: StatePaths) -> Result<WatcherContext<'static>, String> {
        let home = ProcessEnv
            .home_dir()
            .ok_or("watcher: cannot find the home directory — set HOME")?;
        Ok(WatcherContext {
            os: Os::current(),
            paths,
            home,
            exec: &SystemExec,
            env: std::env::vars().collect(),
            names: Names::default(),
            system_root: PathBuf::from(
                ProcessEnv
                    .var("SystemRoot")
                    .unwrap_or_else(|| r"C:\Windows".into()),
            ),
            wait: FIRST_TICK_WAIT,
            clock: &SystemClock,
            current_exe: std::env::current_exe().ok(),
        })
    }
}

/// The outcome of `start` or `stop`, in lines for the terminal.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct WatcherReport {
    pub ok: bool,
    pub lines: Vec<String>,
}

impl WatcherReport {
    fn fail(mut lines: Vec<String>, line: String) -> WatcherReport {
        lines.push(line);
        WatcherReport { ok: false, lines }
    }
}

/// Where each job file goes.
#[derive(Debug, Clone)]
struct Layout {
    script: PathBuf,
    log: PathBuf,
    record: PathBuf,
    /// Windows task definition.
    xml: PathBuf,
    /// macOS agent.
    plist: PathBuf,
    /// Linux units.
    service: PathBuf,
    timer: PathBuf,
}

fn layout(ctx: &WatcherContext<'_>) -> Layout {
    let dir = ctx.paths.root.join("watcher");
    let script = match ctx.os {
        Os::Windows => dir.join("fm-tick.cmd"),
        _ => dir.join("fm-tick.sh"),
    };
    let units = ctx.home.join(".config").join("systemd").join("user");
    Layout {
        script,
        log: ctx.paths.logs_dir().join("tick.log"),
        record: record_path(&ctx.paths),
        xml: dir.join("tick.xml"),
        plist: ctx
            .home
            .join("Library")
            .join("LaunchAgents")
            .join(format!("{}.plist", ctx.names.label)),
        service: units.join(format!("{}.service", ctx.names.unit)),
        timer: units.join(format!("{}.timer", ctx.names.unit)),
    }
}

fn write_file(path: &Path, bytes: &[u8]) -> Result<(), String> {
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir)
            .map_err(|e| format!("watcher: cannot create {} — {e}", dir.display()))?;
    }
    std::fs::write(path, bytes)
        .map_err(|e| format!("watcher: cannot write {} — {e}", path.display()))
}

fn uid(ctx: &WatcherContext<'_>) -> Result<u32, String> {
    let r = ctx.exec.exec(&macos::uid_command());
    r.stdout
        .trim()
        .parse()
        .ok()
        .filter(|_| r.ok())
        .ok_or_else(|| format!("watcher: cannot find your user id — {}", r.first_line()))
}

fn age_words(d: chrono::Duration) -> String {
    let s = d.num_seconds().max(0);
    match s {
        0..60 => format!("{s}s"),
        60..3600 => format!("{}m", s / 60),
        3600..86_400 => format!("{}h", s / 3600),
        _ => format!("{}d", s / 86_400),
    }
}

/// What the job was registered as, ready to write.
struct Plan {
    method: Method,
    job_name: String,
    /// `(path, bytes)` to write.
    files: Vec<(PathBuf, Vec<u8>)>,
    /// Commands that must succeed, in order; the first may be a cleanup that is allowed to fail.
    register: Vec<Cmd>,
    /// Commands whose failure does not matter (unloading an old copy first).
    prepare: Vec<Cmd>,
    run_now: Option<Cmd>,
}

fn plan(ctx: &WatcherContext<'_>, spec: &JobSpec, lay: &Layout) -> Result<Plan, String> {
    let names = &ctx.names;
    match ctx.os {
        Os::Windows => {
            let headless = ctx
                .system_root
                .join("System32")
                .join("conhost.exe")
                .is_file();
            let launcher = windows::launcher(&ctx.system_root, &lay.script, headless)?;
            let xml = windows::task_xml(spec, &launcher);
            let cmd = windows::tick_cmd(spec);
            assert_no_secrets(&xml, &ctx.env)?;
            assert_no_secrets(&cmd, &ctx.env)?;
            Ok(Plan {
                method: Method::Schtasks,
                job_name: names.task.clone(),
                files: vec![
                    (lay.script.clone(), cmd.into_bytes()),
                    (lay.xml.clone(), windows::utf16_with_bom(&xml)),
                ],
                register: windows::register(&names.task, &lay.xml),
                prepare: Vec::new(),
                run_now: Some(windows::run_now(&names.task)),
            })
        }
        Os::MacOs => {
            let uid = uid(ctx)?;
            let sh = unix::tick_sh(spec, &macos::unregister_lines(&names.label, &lay.plist));
            let plist = macos::plist(spec);
            assert_no_secrets(&sh, &ctx.env)?;
            assert_no_secrets(&plist, &ctx.env)?;
            let (bootout, bootstrap) = macos::register(uid, &names.label, &lay.plist);
            Ok(Plan {
                method: Method::Launchd,
                job_name: names.label.clone(),
                files: vec![
                    (lay.script.clone(), sh.into_bytes()),
                    (lay.plist.clone(), plist.into_bytes()),
                ],
                register: vec![bootstrap],
                prepare: vec![bootout],
                run_now: Some(macos::run_now(uid, &names.label)),
            })
        }
        Os::Linux => {
            if ctx.exec.exec(&linux::probe_systemd()).ok() {
                let sh = unix::tick_sh(
                    spec,
                    &linux::unregister_lines(&names.unit, &[&lay.service, &lay.timer]),
                );
                let service = linux::service_unit(spec);
                let timer = linux::timer_unit(&names.unit);
                assert_no_secrets(&sh, &ctx.env)?;
                assert_no_secrets(&service, &ctx.env)?;
                return Ok(Plan {
                    method: Method::Systemd,
                    job_name: format!("{}.timer", names.unit),
                    files: vec![
                        (lay.script.clone(), sh.into_bytes()),
                        (lay.service.clone(), service.into_bytes()),
                        (lay.timer.clone(), timer.into_bytes()),
                    ],
                    register: linux::register(&names.unit),
                    prepare: Vec::new(),
                    run_now: Some(linux::run_now(&names.unit)),
                });
            }
            let listed = ctx.exec.exec(&linux::crontab_list());
            if listed.code.is_none() {
                return Err(
                    "watcher: this machine has no systemd user session and no crontab — keep fm serve running instead"
                        .into(),
                );
            }
            let existing = if listed.ok() {
                listed.stdout.clone()
            } else {
                String::new()
            };
            let sh = unix::tick_sh(spec, &linux::cron_unregister_lines(&names.unit));
            let line = linux::crontab_line(spec);
            assert_no_secrets(&sh, &ctx.env)?;
            assert_no_secrets(&line, &ctx.env)?;
            Ok(Plan {
                method: Method::Crontab,
                job_name: linux::cron_marker(&names.unit),
                files: vec![(lay.script.clone(), sh.into_bytes())],
                register: vec![linux::crontab_install(&linux::crontab_with(
                    &existing,
                    &line,
                    &names.unit,
                ))],
                prepare: Vec::new(),
                run_now: None,
            })
        }
    }
}

#[cfg(unix)]
fn make_executable(path: &Path) {
    use std::os::unix::fs::PermissionsExt;
    let _ = std::fs::set_permissions(path, std::fs::Permissions::from_mode(0o700));
}

#[cfg(not(unix))]
fn make_executable(_path: &Path) {}

/// Register the job for `exe` and wait for its first tick.
pub fn start(ctx: &WatcherContext<'_>, exe: &Path) -> WatcherReport {
    let mut lines = Vec::new();
    let exe = std::path::absolute(exe).unwrap_or_else(|_| exe.to_path_buf());
    if !exe.is_file() {
        return WatcherReport::fail(
            lines,
            format!(
                "watcher: {} not found — run it from the fm you installed",
                exe.display()
            ),
        );
    }
    if let Err(e) = fm_state::open_state(&ctx.paths) {
        return WatcherReport::fail(lines, format!("watcher: {e}"));
    }
    let store = StateStore::new(&ctx.paths);
    let before = store.load();
    let now = ctx.clock.now();
    let serve_ticking = before.last_tick_by == Some(TickSource::Serve)
        && before
            .last_tick_at
            .as_deref()
            .and_then(parse_iso)
            .is_some_and(|t| now - t <= chrono::Duration::minutes(2));
    if serve_ticking {
        return WatcherReport::fail(
            lines,
            "watcher: fm serve is ticking — one clock at a time: stop fm serve, then fm watcher start"
                .into(),
        );
    }

    let snap = snapshot_env(&ctx.env, &ctx.paths.root);
    if !snap.refused.is_empty() {
        lines.push(format!(
            "not carried into the job: {} — credentials never are",
            snap.refused.join(", ")
        ));
    }
    let lay = layout(ctx);
    let spec = JobSpec {
        exe: exe.clone(),
        state_dir: ctx.paths.root.clone(),
        env: snap.vars.clone(),
        names: ctx.names.clone(),
        script: lay.script.clone(),
        log: lay.log.clone(),
        record: lay.record.clone(),
    };
    let plan = match plan(ctx, &spec, &lay) {
        Ok(p) => p,
        Err(e) => return WatcherReport::fail(lines, e),
    };
    for (path, bytes) in &plan.files {
        if let Err(e) = write_file(path, bytes) {
            return WatcherReport::fail(lines, e);
        }
    }
    make_executable(&lay.script);
    for c in &plan.prepare {
        let _ = ctx.exec.exec(c);
    }
    for c in &plan.register {
        let r = ctx.exec.exec(c);
        if !r.ok() {
            return WatcherReport::fail(
                lines,
                format!("watcher: could not register the job — {}", r.first_line()),
            );
        }
    }
    let record = WatcherRecord {
        version: 1,
        method: plan.method,
        job_name: plan.job_name.clone(),
        exe,
        installed_at: iso(now),
        files: plan.files.iter().map(|(p, _)| p.clone()).collect(),
        refused: snap.refused.clone(),
    };
    let json = serde_json::to_string_pretty(&record).unwrap_or_default();
    if let Err(e) = write_file(&lay.record, json.as_bytes()) {
        return WatcherReport::fail(lines, e);
    }
    lines.push(format!(
        "watcher: on ({}) · {}",
        plan.method.word(),
        plan.job_name
    ));

    if ctx.wait.is_zero() {
        return WatcherReport { ok: true, lines };
    }
    // Registering is not evidence. Ask for a tick now and wait for one to land.
    if let Some(c) = &plan.run_now {
        let _ = ctx.exec.exec(c);
    }
    let deadline = ctx.clock.now()
        + chrono::Duration::from_std(ctx.wait).unwrap_or(chrono::Duration::seconds(90));
    loop {
        let st = store.load();
        let by_job = st.last_tick_by == Some(TickSource::Job);
        let moved =
            st.last_tick_at != before.last_tick_at || before.last_tick_by != Some(TickSource::Job);
        if by_job && moved {
            lines.push("first tick ok".into());
            return WatcherReport { ok: true, lines };
        }
        if ctx.clock.now() >= deadline {
            break;
        }
        ctx.clock.sleep(Duration::from_secs(1));
    }
    WatcherReport::fail(
        lines,
        format!(
            "first tick did not arrive within {}s — check {} and fm watcher status",
            ctx.wait.as_secs(),
            lay.log.display()
        ),
    )
}

fn remove_files(files: &[&Path]) {
    for f in files {
        let _ = std::fs::remove_file(f);
    }
}

fn remove_cron(ctx: &WatcherContext<'_>) -> ExecResult {
    let listed = ctx.exec.exec(&linux::crontab_list());
    let marker = linux::cron_marker(&ctx.names.unit);
    if !listed.ok() || !listed.stdout.lines().any(|l| l.ends_with(&marker)) {
        return ExecResult {
            code: Some(1),
            stdout: String::new(),
            stderr: "no crontab line".into(),
        };
    }
    ctx.exec
        .exec(&linux::crontab_install(&linux::crontab_without(
            &listed.stdout,
            &ctx.names.unit,
        )))
}

/// Remove the job and its files. Safe when nothing is registered.
pub fn stop(ctx: &WatcherContext<'_>) -> WatcherReport {
    let record = read_record(&ctx.paths);
    let lay = layout(ctx);
    let methods: Vec<Method> = match (&record, ctx.os) {
        (Some(r), _) => vec![r.method],
        (None, Os::Windows) => vec![Method::Schtasks],
        (None, Os::MacOs) => vec![Method::Launchd],
        (None, Os::Linux) => vec![Method::Systemd, Method::Crontab],
    };
    let mut removed = Vec::new();
    let mut problems = Vec::new();
    for m in methods {
        let result = match m {
            Method::Schtasks => windows::remove(&ctx.names.task)
                .iter()
                .map(|c| ctx.exec.exec(c))
                .next_back(),
            Method::Launchd => match uid(ctx) {
                Ok(uid) => macos::remove(uid, &ctx.names.label)
                    .iter()
                    .map(|c| ctx.exec.exec(c))
                    .next_back(),
                Err(e) => {
                    problems.push(e);
                    None
                }
            },
            Method::Systemd => {
                let r = linux::remove(&ctx.names.unit)
                    .iter()
                    .map(|c| ctx.exec.exec(c))
                    .next_back();
                remove_files(&[&lay.service, &lay.timer]);
                let _ = ctx.exec.exec(&linux::reload());
                r
            }
            Method::Crontab => Some(remove_cron(ctx)),
        };
        match result {
            Some(r) if r.ok() => removed.push(m.word()),
            Some(r) if record.is_some() => problems.push(format!(
                "the {} job may already be gone — {}",
                m.word(),
                r.first_line()
            )),
            _ => {}
        }
    }
    let mut files: Vec<PathBuf> = vec![lay.script.clone(), lay.record.clone()];
    match ctx.os {
        Os::Windows => files.push(lay.xml.clone()),
        Os::MacOs => files.push(lay.plist.clone()),
        Os::Linux => {}
    }
    if let Some(r) = &record {
        files.extend(r.files.iter().cloned());
    }
    remove_files(&files.iter().map(PathBuf::as_path).collect::<Vec<_>>());

    let mut lines = Vec::new();
    match (removed.is_empty(), record.is_some()) {
        (false, _) => lines.push(format!(
            "watcher: off — job removed ({})",
            removed.join(", ")
        )),
        (true, true) => lines.push("watcher: off".into()),
        (true, false) => lines.push("watcher: off — it was not registered".into()),
    }
    lines.extend(problems);
    WatcherReport { ok: true, lines }
}

/// What the watcher is doing.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum WatcherState {
    /// Not registered, and `fm serve` is not ticking either.
    Off,
    /// Registered and ticking (or registered moments ago).
    On,
    /// Registered, but quiet, lost by the scheduler, or registered for another executable.
    Late,
    /// Not registered, but `fm serve` ticked in the last five minutes.
    Serve,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct WatcherStatus {
    pub state: WatcherState,
    /// One line for a status bar: `on — last tick 12s ago`, `off — fm watcher start`, …
    pub summary: String,
    /// Everything `fm watcher status` prints.
    pub lines: Vec<String>,
    pub record: Option<WatcherRecord>,
    pub last_tick_at: Option<String>,
    pub last_tick_by: Option<TickSource>,
}

fn job_present(ctx: &WatcherContext<'_>, method: Method) -> Result<bool, String> {
    let r = match method {
        Method::Schtasks => ctx.exec.exec(&windows::query(&ctx.names.task)),
        Method::Launchd => ctx.exec.exec(&macos::query(uid(ctx)?, &ctx.names.label)),
        Method::Systemd => ctx.exec.exec(&linux::query(&ctx.names.unit)),
        Method::Crontab => {
            let r = ctx.exec.exec(&linux::crontab_list());
            let marker = linux::cron_marker(&ctx.names.unit);
            return Ok(r.ok() && r.stdout.lines().any(|l| l.ends_with(&marker)));
        }
    };
    Ok(r.ok())
}

/// The watcher's state. `deep` also asks the scheduler whether it still has the job (slower).
pub fn status(ctx: &WatcherContext<'_>, deep: bool) -> WatcherStatus {
    let now = ctx.clock.now();
    let st = StateStore::new(&ctx.paths).load();
    let record = read_record(&ctx.paths);
    let last = st.last_tick_at.as_deref().and_then(parse_iso);
    let age = last.map(|t| now - t);
    let quiet = chrono::Duration::from_std(QUIET).unwrap_or(chrono::Duration::minutes(5));
    let ticking = age.is_some_and(|a| a <= quiet);
    let ago = age.map(age_words);
    let by = st.last_tick_by;
    let by_word = |b: Option<TickSource>| match b {
        Some(TickSource::Job) => ", by the watcher",
        Some(TickSource::Serve) => ", by fm serve",
        Some(TickSource::Cli) => ", by fm tick",
        None => "",
    };
    let tick_line = match (&st.last_tick_at, &ago) {
        (Some(at), Some(a)) => format!("  last tick: {at} ({a} ago{})", by_word(by)),
        _ => "  last tick: never".to_string(),
    };

    let Some(rec) = record else {
        let serve = ticking && by == Some(TickSource::Serve);
        let (state, summary, mut lines) = if serve {
            (
                WatcherState::Serve,
                format!(
                    "on (fm serve) — last tick {} ago",
                    ago.clone().unwrap_or_default()
                ),
                vec!["watcher: off — fm serve is ticking instead".to_string()],
            )
        } else if ticking && by == Some(TickSource::Job) {
            // Ticking from a job this folder has no record of (watcher.json removed by hand, or
            // another state folder's job pointed here): it is on, whatever registered it.
            (
                WatcherState::On,
                format!("on — last tick {} ago", ago.clone().unwrap_or_default()),
                vec![
                    "watcher: on — but watcher.json is missing; fm watcher start rewrites it"
                        .to_string(),
                ],
            )
        } else {
            (
                WatcherState::Off,
                "off — fm watcher start".to_string(),
                vec![
                    "watcher: off — no schedule fires and no watch is checked on its own".into(),
                    "  start it with: fm watcher start".into(),
                    "  or keep this running in a terminal: fm serve".into(),
                ],
            )
        };
        lines.push(tick_line);
        return WatcherStatus {
            state,
            summary,
            lines,
            record: None,
            last_tick_at: st.last_tick_at,
            last_tick_by: by,
        };
    };

    let mut lines = vec![format!(
        "watcher: on ({}) · {}",
        rec.method.word(),
        rec.job_name
    )];
    let mut problem: Option<String> = None;
    let mut other_executable = false;
    if !rec.exe.is_file() {
        let p = format!("{} is gone", rec.exe.display());
        lines.push(format!("  stale: {p}"));
        problem.get_or_insert(p);
    } else if let Some(cur) = ctx.current_exe.as_ref().filter(|c| !same_path(c, &rec.exe)) {
        lines.push(format!(
            "  stale: registered for {}, this is {}",
            rec.exe.display(),
            cur.display()
        ));
        lines.push("  keep the registered executable until you choose to migrate".into());
        other_executable = true;
        problem.get_or_insert("registered for another executable".into());
    }
    if deep {
        match job_present(ctx, rec.method) {
            Ok(true) => lines.push("  job: present".into()),
            Ok(false) => {
                lines.push("  job: NOT found by the scheduler".into());
                problem.get_or_insert("the scheduler lost the job".into());
            }
            Err(e) => lines.push(format!("  job: {e}")),
        }
    }
    lines.push(tick_line);
    if !rec.refused.is_empty() {
        lines.push(format!(
            "  not carried into the job: {} — credentials never are",
            rec.refused.join(", ")
        ));
    }
    match rec.method {
        Method::Systemd => lines.push(
            "  note: without a login session the timer stops; to keep it: loginctl enable-linger $USER"
                .into(),
        ),
        Method::Crontab => lines.push("  note: ticking from crontab (no systemd user session)".into()),
        _ => {}
    }
    let log = ctx.paths.logs_dir().join("tick.log");
    if let Ok(text) = std::fs::read_to_string(&log) {
        let tail: Vec<&str> = text.lines().filter(|l| !l.trim().is_empty()).collect();
        for l in tail.iter().skip(tail.len().saturating_sub(3)) {
            lines.push(format!("  log: {l}"));
        }
    }

    let installed = parse_iso(&rec.installed_at);
    let fresh = installed.is_some_and(|t| now - t <= chrono::Duration::minutes(2));
    let (state, summary) = match (problem, &ago) {
        (Some(p), _) if other_executable => (
            WatcherState::Late,
            format!("late — {p} — review before migrating"),
        ),
        (Some(p), _) => (WatcherState::Late, format!("late — {p} — fm watcher start")),
        (None, Some(a)) if ticking => (WatcherState::On, format!("on — last tick {a} ago")),
        (None, _) if fresh && last.is_none_or(|t| installed.is_some_and(|i| t < i)) => (
            WatcherState::On,
            "on — waiting for the first tick".to_string(),
        ),
        (None, Some(a)) => {
            lines.push(
                "  the last tick is over five minutes old — the job may not be running".into(),
            );
            (
                WatcherState::Late,
                format!("late — last tick {a} ago — fm watcher start"),
            )
        }
        (None, None) => (
            WatcherState::Late,
            "late — it has never ticked — fm watcher start".to_string(),
        ),
    };
    WatcherStatus {
        state,
        summary,
        lines,
        record: Some(rec),
        last_tick_at: st.last_tick_at,
        last_tick_by: by,
    }
}

fn system_ctx() -> Result<WatcherContext<'static>, String> {
    let paths = fm_state::state_paths().map_err(|e| format!("watcher: {e}"))?;
    WatcherContext::system(paths)
}

/// `fm watcher start`: register the job for `exe` (the running `fm`) on this machine and wait up
/// to 90 seconds for its first tick.
pub fn watcher_start(exe: &Path) -> WatcherReport {
    match system_ctx() {
        Ok(ctx) => start(&ctx, exe),
        Err(e) => WatcherReport::fail(Vec::new(), e),
    }
}

/// `fm watcher stop`: remove the job on this machine.
pub fn watcher_stop() -> WatcherReport {
    match system_ctx() {
        Ok(ctx) => stop(&ctx),
        Err(e) => WatcherReport::fail(Vec::new(), e),
    }
}

/// `fm watcher status`, asking the scheduler too.
pub fn watcher_status() -> WatcherStatus {
    match system_ctx() {
        Ok(ctx) => status(&ctx, true),
        Err(e) => WatcherStatus {
            state: WatcherState::Off,
            summary: format!("off — {e}"),
            lines: vec![e],
            record: None,
            last_tick_at: None,
            last_tick_by: None,
        },
    }
}

/// The age of an ISO time at `now`, in listing words (`12s`, `4m`, `2h`, `3d`).
pub fn ago(at: &str, now: DateTime<Utc>) -> Option<String> {
    parse_iso(at).map(|t| age_words(now - t))
}

